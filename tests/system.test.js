const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const source = fs.readFileSync(path.join(__dirname, '..', 'app.js'), 'utf8');
const start = source.indexOf('const FILO_TEST_KOLEKSIYONLARI =');
const end = source.indexOf('\nfunction backupToJson(', start);
assert.ok(start >= 0 && end > start, 'System test functions must exist');
const names = ['vehicles', 'expenses', 'activityLog', 'sozlesmeler', 'arsiv', 'arsivSilinenler', 'customers', 'rentals', 'invoices', 'payments', 'ledger', 'suppliers', 'supplierLedger', 'serviceParts', 'tires', 'fuelRecords', 'tolls', 'trafficFines', 'documents', 'notifications', 'automationRules', 'kvkkTalepleri', 'leads', 'ihaleler', 'sozlesmeGruplari'];
const context = {window: {}, Date, JSON, Set, Number, Array, String, todayISO: () => '2026-01-01', daysLeft: () => 0, normPlaka: value => String(value).toUpperCase().replace(/\s+/g, ''), validPlaka: value => /^\d{2}[A-Z]{1,3}\d{2,5}$/.test(value)};
for (const name of names) context[name] = [];
vm.createContext(context);
vm.runInContext(source.slice(start, end), context);
context.vehicles.push({id: 'vehicle-1', plaka: '34ABC123'});
context.sozlesmeler.push({id: 'contract-1', data: {}});
context.rentals.push({id: 'active', vehicleId: 'vehicle-1', sozlesmeId: 'contract-1', durum: 'teslimEdildi'});
context.rentals.push({id: 'closed', vehicleId: 'old-deleted-vehicle', durum: 'kapandi', teslimKontrol: {km: 1000}, iadeKontrol: {km: 1100}});
const before = JSON.stringify(names.map(name => context[name]));
assert.equal(context.window.filoSistemTesti(false).hata, 0, 'Valid active and closed rentals must pass');
assert.equal(JSON.stringify(names.map(name => context[name])), before, 'Checks must not modify records');
context.rentals[0].vehicleId = 'missing';
assert.ok(context.window.filoSistemTesti(false).sonuclar.some(result => result.ad.startsWith('Kiralamalar: her aktif') && !result.ok));
context.rentals[0].vehicleId = 'vehicle-1';
context.rentals[0].sozlesmeId = 'missing';
assert.ok(context.window.filoSistemTesti(false).sonuclar.some(result => result.ad.startsWith('Kiralamalar: bağlı') && !result.ok));
context.rentals[0].sozlesmeId = 'contract-1';
context.rentals[1].iadeKontrol.km = 100;
assert.ok(context.window.filoSistemTesti(false).sonuclar.some(result => result.ad.startsWith('İade kayıtları') && !result.ok));
context.rentals[1].iadeKontrol.km = 1100;
context.documents = undefined;
assert.ok(context.window.filoSistemTesti(false).sonuclar.some(result => result.ad.startsWith('Yedek JSON:') && !result.ok));
console.log('Read-only backup, contract and return checks passed.');
